#!/usr/bin/env python3
"""Build rules/index.md: one line per rule, taken from the rule headings.

Run from the repository root after changing any rule heading:
    python3 scripts/build_index.py
"""
import pathlib
import re

ORDER = [
    ("Parts of the text", ["titles", "abstracts", "introduction", "literature-review",
                           "methods", "methods-structure", "results", "discussion"]),
    ("Checks for any part", ["data-commentary", "numbers", "claims", "argument", "sentences",
                             "cohesion", "vagueness", "unpacking", "informativeness"]),
    ("Health research only", ["reporting", "spin"]),
]

root = pathlib.Path(__file__).resolve().parent.parent
out = [
    "# Index of checks",
    "",
    "One line per rule, taken from the rule headings. Use it to choose which checks to run, "
    "then open the rules file for the rule's source and its check. Cite rules by file and number "
    "(for example, \"introduction, rule 7\").",
    "",
    "*Generated by `scripts/build_index.py` from the rule headings; regenerate it after changing a heading.*",
]
for group, names in ORDER:
    out += ["", f"## {group}"]
    for name in names:
        text = (root / "rules" / f"{name}.md").read_text(encoding="utf-8")
        title = text.splitlines()[0].lstrip("# ").strip()
        rules = re.findall(r"(?m)^### (\d+)\. (.+)$", text)
        out += ["", f"### `rules/{name}.md`: {title}", ""]
        out += [f"{n}. {heading}" for n, heading in rules]
(root / "rules" / "index.md").write_text("\n".join(out) + "\n", encoding="utf-8")
